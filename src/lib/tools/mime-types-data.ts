/**
 * Common file extensions and the MIME type each is normally served as.
 *
 * Sorted by extension, one entry per extension (a type may appear under
 * several). The types follow the IANA media type registry where it has one
 * and the widely used `x-` or vendor types where it does not; `note` mentions
 * the alternatives that also appear in the wild.
 */

export type MimeCategory =
  | 'web'
  | 'text'
  | 'data'
  | 'code'
  | 'image'
  | 'audio'
  | 'video'
  | 'font'
  | 'document'
  | 'archive'
  | 'binary';

export interface MimeEntry {
  /** Lowercase, without the dot. */
  ext: string;
  /** Lowercase `type/subtype`. */
  type: string;
  category: MimeCategory;
  /** A caveat or a common alternative. */
  note?: string;
}

